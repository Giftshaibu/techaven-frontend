import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const solar = require("@iconify-json/solar/icons.json");
const names = new Set(["question-circle-linear"]);
async function scan(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await scan(filename);
    else if (/\.tsx?$/.test(filename) && entry.name !== "solar-icons.ts") {
      const source = await readFile(filename, "utf8");
      for (const match of source.matchAll(/["']([a-z0-9-]+-(?:linear|bold|outline|duotone))["']/g)) {
        if (match[1] !== "font-bold") names.add(match[1]);
      }
    }
  }
}
await scan(path.join(root, "src"));
const missing = [...names].filter((name) => !solar.icons[name]);
if (missing.length) throw new Error(`Unknown Solar icons: ${missing.join(", ")}`);
const icons = Object.fromEntries([...names].sort().map((name) => [name, {
  width: solar.width ?? 24, height: solar.height ?? 24, ...solar.icons[name],
}]));
const output = `// Generated by scripts/generate-icons.mjs. Bundle only icons used by this storefront.\nimport type { IconifyIcon } from "@iconify/types";\n\nexport const solarIcons: Record<string, IconifyIcon> = ${JSON.stringify(icons, null, 2)};\n`;
const target = path.join(root, "src/lib/solar-icons.ts");
if (await readFile(target, "utf8").catch(() => "") !== output) await writeFile(target, output);
console.log(`Bundled ${names.size} local Solar icons (${Buffer.byteLength(output)} bytes).`);
