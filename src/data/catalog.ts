export const formatMwk = (value: number) =>
  `MWK ${value.toLocaleString("en-US", { maximumFractionDigits: 0 })}`;

export const getCategory = (slug: string) => categories.find((c) => c.slug === slug);
export const getShop = (slug: string) => shops.find((s) => s.slug === slug);
export const getProduct = (slug: string) => products.find((p) => p.slug === slug);
export const getCatalog = (slug: string) => catalogs.find((c) => c.slug === slug);

export const productsByCategory = (slug: string) => products.filter((p) => p.category === slug);
export const productsByShop = (slug: string) => products.filter((p) => p.shop === slug);
export const productsBySlugs = (slugs: string[]) =>
  slugs.map((s) => getProduct(s)).filter((p): p is Product => Boolean(p));

export const discountPercent = (p: Product) =>
  p.oldPrice ? Math.round(((p.oldPrice - p.price) / p.oldPrice) * 100) : 0;

export const dealProducts = products.filter((p) => p.oldPrice);
export const shopProductCount = (slug: string) => productsByShop(slug).length;
